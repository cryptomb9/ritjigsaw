import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { basename, extname, join } from "node:path";

const PUZZLES_DIR = join(process.cwd(), "public", "puzzles");
const OUTPUT_PATH = join(process.cwd(), "src", "generated", "puzzleManifest.ts");
const DEFAULT_ROWS = 4;
const DEFAULT_COLS = 4;
const IMAGE_EXTENSIONS = new Set([".gif", ".jpeg", ".jpg", ".png", ".svg", ".webp"]);

const STABLE_OVERRIDES = {
  "ritual-placeholder.svg": {
    id: 1,
    title: "Ritual Jigsaw",
    imageAlt: "Ritual themed geometric puzzle artwork",
    imageURI: "ritual-placeholder-v1",
    layoutSeed: "ritual-jigsaw:v1:ritual-placeholder:4x4",
  },
  "MONALISA.jpeg": {
    id: 2,
    title: "Mona Lisa",
    imageAlt: "Mona Lisa puzzle image",
    imageURI: "monalisa-v1",
    layoutSeed: "ritual-jigsaw:v1:monalisa:4x4",
  },
};

if (!existsSync(PUZZLES_DIR)) {
  throw new Error(`Missing puzzle image directory: ${PUZZLES_DIR}`);
}

const usedIds = new Set();
const files = readdirSync(PUZZLES_DIR, { withFileTypes: true })
  .filter((entry) => entry.isFile())
  .map((entry) => entry.name)
  .filter((fileName) => IMAGE_EXTENSIONS.has(extname(fileName).toLowerCase()))
  .sort((a, b) => a.localeCompare(b, undefined, { sensitivity: "base" }));

const entries = files.map((fileName) => {
  const override = STABLE_OVERRIDES[fileName];
  const rows = parseGrid(fileName)?.rows ?? DEFAULT_ROWS;
  const cols = parseGrid(fileName)?.cols ?? DEFAULT_COLS;
  const id = reserveId(override?.id ?? stableId(fileName));
  const sourceTitle = override?.title ?? titleFromFileName(fileName);
  const imageURI = override?.imageURI ?? fileName;

  return {
    id,
    title: sourceTitle,
    imageUrl: `/puzzles/${encodeURIComponent(fileName)}`,
    imageAlt: override?.imageAlt ?? `${sourceTitle} puzzle image`,
    imageURI,
    rows,
    cols,
    layoutSeed: override?.layoutSeed ?? `ritual-jigsaw:v1:${fileName}:${rows}x${cols}`,
  };
})
  .sort((a, b) => a.id - b.id)
  .map((entry, index) => ({
    ...entry,
    title: `${index + 1}`,
    imageAlt: `Puzzle ${index + 1} image`,
  }));

const source = `// Generated by scripts/generate-puzzle-manifest.mjs. Do not edit by hand.
export type GeneratedPuzzleManifestEntry = {
  id: number;
  title: string;
  imageUrl: string;
  imageAlt: string;
  imageURI: string;
  rows: number;
  cols: number;
  layoutSeed: string;
};

export const GENERATED_PUZZLE_MANIFEST = ${JSON.stringify(entries, null, 2)} as const satisfies readonly GeneratedPuzzleManifestEntry[];
`;

mkdirSync(join(process.cwd(), "src", "generated"), { recursive: true });

if (!existsSync(OUTPUT_PATH) || readFileSync(OUTPUT_PATH, "utf8") !== source) {
  writeFileSync(OUTPUT_PATH, source);
}

console.log(`Generated ${entries.length} puzzle manifest entries.`);

function parseGrid(fileName) {
  const match = basename(fileName, extname(fileName)).match(/(?:^|[-_])([2-9])x([2-9])(?:$|[-_])/i);

  if (!match) {
    return null;
  }

  return {
    rows: Number(match[1]),
    cols: Number(match[2]),
  };
}

function titleFromFileName(fileName) {
  return basename(fileName, extname(fileName))
    .replace(/[-_]+/g, " ")
    .replace(/\b\w/g, (letter) => letter.toUpperCase())
    .replace(/\s+/g, " ")
    .trim();
}

function stableId(value) {
  let hash = 2166136261;

  for (const char of value) {
    hash ^= char.charCodeAt(0);
    hash = Math.imul(hash, 16777619);
  }

  return 1000 + (hash >>> 0);
}

function reserveId(id) {
  let nextId = id;

  while (usedIds.has(nextId)) {
    nextId += 1;
  }

  usedIds.add(nextId);
  return nextId;
}
